"use client";

import { useState } from "react";
import { Sparkles } from "lucide-react";
import { PageHeader } from "@/components/shared/page-header";
import { Stagger, StaggerItem } from "@/components/shared/motion";
import { InsightCard } from "@/components/insights/insight-card";
import { Segmented } from "@/components/ui/misc";
import { EmptyState } from "@/components/shared/states";
import { Card, CardBody } from "@/components/ui/card";
import { useAnalysis } from "@/lib/store/use-analysis";
import type { InsightCategory } from "@/types/insights";

type Filter = "all" | InsightCategory;

export default function InsightsPage() {
  const { insights } = useAnalysis();
  const [filter, setFilter] = useState<Filter>("all");
  const count = (c: InsightCategory) => insights.filter((i) => i.category === c).length;
  const shown = insights.filter((i) => filter === "all" || i.category === filter);

  return (
    <Stagger>
      <StaggerItem><PageHeader icon={Sparkles} accent="lime" eyebrow="Intelligence feed" title="Insights" subtitle="Every insight is computed from your data and links to the evidence behind it." /></StaggerItem>
      <StaggerItem>
        <div className="mb-4 flex flex-wrap items-center justify-between gap-3">
          <Segmented<Filter> id="ins-filter" ariaLabel="Insight category" value={filter} onChange={setFilter}
            options={[{ value: "all", label: `All (${insights.length})` }, { value: "drift", label: `Drift (${count("drift")})` }, { value: "experiment", label: `Experiments (${count("experiment")})` }, { value: "movement", label: `Movement (${count("movement")})` }, { value: "brain-body", label: `Brain-Body (${count("brain-body")})` }, { value: "pattern", label: `Patterns (${count("pattern")})` }]} />
          <p className="text-xs text-muted">Insights use the full 90-day history and the selected data source.</p>
        </div>
      </StaggerItem>
      <StaggerItem>
        {shown.length === 0 ? <EmptyState title="No insights for this selection" text="Try another category or switch to the Combined data source to include more measurements." /> : (
          <div className="space-y-3">{shown.map((i) => <InsightCard key={i.id} insight={i} />)}</div>
        )}
      </StaggerItem>
      <StaggerItem className="mt-6">
        <Card><CardBody className="text-xs leading-relaxed text-muted">
          <p className="mb-1 text-sm font-medium text-fg">How to read these insights</p>
          Insights are generated by deterministic analytics running in your browser — baselines and z-scores, rolling averages, persistence checks, before/after comparisons and Pearson correlations. No external AI service is used. Correlation and experiment results describe <span className="text-fg">associations in your own data</span>; they do not show cause and effect, and none of them is a diagnosis. Confidence reflects sample size, data completeness, consistency and concurrent changes.
        </CardBody></Card>
      </StaggerItem>
    </Stagger>
  );
}
